# 📱 Mobile API — واجهة برمجية موحّدة لتطبيقات الأندرويد و iOS (Flutter).
#
# يعرّض هذا التطبيق طبقة REST نظيفة ومُصمّمة خصيصاً لتطبيق الموبايل، تغطّي:
#   • تسجيل الدخول عبر JWT (access + refresh) وبيانات المستخدم.
#   • لوحة معلومات مُلخّصة (مؤشرات الورشة والمخزون).
#   • أوامر شغل الورشة والصيانة (SaleInvoice من نوع maintenance) مع تحديث الحالة.
#   • المخزون وقطع الغيار (Product / Inventory) والبحث وتنبيهات النقص.
#   • العملاء والمركبات (قراءة).
#
